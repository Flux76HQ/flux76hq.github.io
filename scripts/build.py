#!/usr/bin/env python3
"""Build the Flux76.com pages from templates and one content file per language.

    python3 scripts/build.py          write every page in PAGES
    python3 scripts/build.py --check  exit 1 if a committed page is out of date

The generated pages are committed: GitHub Pages serves this repository as-is,
so there is no deploy step that could run this for us. Python standard library
only; no dependencies.

Sources:
    src/index.template.html   the home page
    src/legal.template.html   the privacy statement and the terms
    src/partials/*.html       shared pieces, included with {{> name}}
    src/content/<lang>.json   all short text, per language
    src/legal/<lang>/<doc>.html  the body of a legal page, as HTML

Placeholders in templates and partials:
    {{> name}}  the partial src/partials/name.html
    {{key}}    the value as written (may contain HTML)
    {{a:key}}  escaped for use inside an HTML attribute
    {{j:key}}  escaped for use inside a JSON string (the JSON-LD block)
    {{u:key}}  percent-encoded for use inside a URL (the mailto link)

Keys starting with an underscore that are not in the content files are set
per page by this script (paths, the legal document's title and body).
"""
import html
import json
import re
import sys
from dataclasses import dataclass
from datetime import date
from pathlib import Path
from urllib.parse import quote

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
CONTENT = SRC / "content"
PARTIALS = SRC / "partials"
LEGAL = SRC / "legal"
INCLUDE = re.compile(r"\{\{> ([a-z0-9_-]+)\}\}")
PLACEHOLDER = re.compile(r"\{\{(?:([aju]):)?([a-z0-9_]+)\}\}")
HEADER = "<!-- Generated by scripts/build.py from src/. Do not edit; edit src/ and rebuild. -->\n"
MONTHS = {
    "en": "January February March April May June July August September October November December",
    "nl": "januari februari maart april mei juni juli augustus september oktober november december",
}


@dataclass(frozen=True)
class Page:
    lang: str
    template: str      # name of src/<template>.template.html
    out: str           # output file, relative to the repository root
    path: str          # URL path
    en_path: str       # the English version of this page
    nl_path: str       # the Dutch version of this page
    doc: str = ""      # legal document: src/legal/<lang>/<doc>.html
    updated: str = ""  # legal document: date it last changed, YYYY-MM-DD


PRIVACY = dict(template="legal", doc="privacy", updated="2026-11-15", en_path="/privacy/", nl_path="/nl/privacy/")
TERMS = dict(template="legal", doc="terms", updated="2026-11-15", en_path="/terms/", nl_path="/nl/voorwaarden/")
PAGES = [
    Page("en", "index", "index.html", "/", "/", "/nl/"),
    Page("nl", "index", "nl/index.html", "/nl/", "/", "/nl/"),
    Page("en", out="privacy/index.html", path="/privacy/", **PRIVACY),
    Page("nl", out="nl/privacy/index.html", path="/nl/privacy/", **PRIVACY),
    Page("en", out="terms/index.html", path="/terms/", **TERMS),
    Page("nl", out="nl/voorwaarden/index.html", path="/nl/voorwaarden/", **TERMS),
]


def load(lang):
    return json.loads((CONTENT / f"{lang}.json").read_text(encoding="utf-8"))


def source(template):
    """The template with its partials expanded."""
    text = (SRC / f"{template}.template.html").read_text(encoding="utf-8")
    for _ in range(5):  # partials may include partials; stop runaway nesting
        if not INCLUDE.search(text):
            return text
        text = INCLUDE.sub(lambda m: (PARTIALS / f"{m.group(1)}.html").read_text(encoding="utf-8").rstrip("\n"), text)
    raise SystemExit(f"{template}: partials nested too deeply")


def template_keys():
    """Every content key a template, partial or legal document uses."""
    texts = [source(t) for t in {p.template for p in PAGES}]
    texts += [f.read_text(encoding="utf-8") for f in LEGAL.glob("*/*.html")]
    keys = {m.group(2) for text in texts for m in PLACEHOLDER.finditer(text)}
    keys |= {f"{p.doc}_{field}" for p in PAGES if p.doc for field in ("title", "desc")}
    return keys


def page_values(page, content):
    home = "/" if page.lang == "en" else "/nl/"
    alt_lang = "nl" if page.lang == "en" else "en"
    values = {
        "_path": page.path,
        "_en_path": page.en_path,
        "_nl_path": page.nl_path,
        "_alt_path": page.nl_path if page.lang == "en" else page.en_path,
        "_alt_lang": alt_lang,
        "_home_path": home,
        # In-page links on the home page stay plain anchors; other pages link back to it.
        "_home": "" if page.path == home else home,
        "_privacy_path": PRIVACY[f"{page.lang}_path"],
        "_terms_path": TERMS[f"{page.lang}_path"],
    }
    if page.doc:
        y, m, d = (int(x) for x in page.updated.split("-"))
        values.update({
            "_doc_title": content[f"{page.doc}_title"],
            "_doc_desc": content[f"{page.doc}_desc"],
            "_doc_updated": date(y, m, d).isoformat(),
            "_doc_updated_label": f"{d} {MONTHS[page.lang].split()[m - 1]} {y}",
            "_doc_body": (LEGAL / page.lang / f"{page.doc}.html").read_text(encoding="utf-8").rstrip("\n"),
        })
    return values


def render(page):
    content = load(page.lang)
    content.update(page_values(page, content))
    text = source(page.template)
    if page.doc:  # the body may use content keys too
        text = text.replace("{{_doc_body}}", content.pop("_doc_body"))

    def sub(match):
        mode, key = match.groups()
        if key not in content:
            raise SystemExit(f"{page.out}: missing key '{key}'")
        value = content[key]
        if mode == "a":
            return html.escape(value, quote=True)
        if mode == "j":
            return json.dumps(value, ensure_ascii=False)[1:-1]
        if mode == "u":
            return quote(value, safe="")
        return value

    out = PLACEHOLDER.sub(sub, text)
    doctype, rest = out.split("\n", 1)
    return f"{doctype}\n{HEADER}{rest}"


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for page in PAGES:
        out = ROOT / page.out
        text = render(page)
        if check:
            if not out.exists() or out.read_text(encoding="utf-8") != text:
                stale.append(page.out)
        else:
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(text, encoding="utf-8")
            print(f"wrote {page.out}")
    if stale:
        print("Out of date: " + ", ".join(stale) + ". Run: python3 scripts/build.py")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
