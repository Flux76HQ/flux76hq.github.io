#!/usr/bin/env python3
"""Build the Flux76.com pages from one template and one content file per language.

    python3 scripts/build.py          write index.html and nl/index.html
    python3 scripts/build.py --check  exit 1 if the committed pages are out of date

The generated pages are committed: GitHub Pages serves this repository as-is,
so there is no deploy step that could run this for us. Python standard library
only; no dependencies.

Placeholders in src/index.template.html:
    {{key}}    the value as written (may contain HTML)
    {{a:key}}  escaped for use inside an HTML attribute
    {{j:key}}  escaped for use inside a JSON string (the JSON-LD block)
    {{u:key}}  percent-encoded for use inside a URL (the mailto link)
"""
import html
import json
import re
import sys
from pathlib import Path
from urllib.parse import quote

ROOT = Path(__file__).resolve().parent.parent
TEMPLATE = ROOT / "src" / "index.template.html"
CONTENT = ROOT / "src" / "content"
PAGES = {"en": "index.html", "nl": "nl/index.html"}
PLACEHOLDER = re.compile(r"\{\{(?:([aju]):)?([a-z0-9_]+)\}\}")
HEADER = "<!-- Generated by scripts/build.py from src/. Do not edit; edit src/ and rebuild. -->\n"


def load(lang):
    return json.loads((CONTENT / f"{lang}.json").read_text(encoding="utf-8"))


def template_keys():
    return {m.group(2) for m in PLACEHOLDER.finditer(TEMPLATE.read_text(encoding="utf-8"))}


def render(lang):
    content = load(lang)

    def sub(match):
        mode, key = match.groups()
        if key not in content:
            raise SystemExit(f"{lang}.json: missing key '{key}' used in the template")
        value = content[key]
        if mode == "a":
            return html.escape(value, quote=True)
        if mode == "j":
            return json.dumps(value, ensure_ascii=False)[1:-1]
        if mode == "u":
            return quote(value, safe="")
        return value

    page = PLACEHOLDER.sub(sub, TEMPLATE.read_text(encoding="utf-8"))
    doctype, rest = page.split("\n", 1)
    return f"{doctype}\n{HEADER}{rest}"


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for lang, rel in PAGES.items():
        out = ROOT / rel
        page = render(lang)
        if check:
            if not out.exists() or out.read_text(encoding="utf-8") != page:
                stale.append(rel)
        else:
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(page, encoding="utf-8")
            print(f"wrote {rel}")
    if stale:
        print("Out of date: " + ", ".join(stale) + ". Run: python3 scripts/build.py")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
